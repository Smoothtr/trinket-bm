import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repository = "thanglequoc/vietnamese-provinces-database";
const datasetPath = "json/vn_only_simplified_json_generated_data_vn_units_minified.json";
const sources = {
  current: {
    revision: "d10fd83c4bf7a5839a56706f1c04f13133271cfc",
    url: `https://raw.githubusercontent.com/${repository}/d10fd83c4bf7a5839a56706f1c04f13133271cfc/${datasetPath}`,
  },
  legacy: {
    revision: "v2.4.1",
    url: `https://raw.githubusercontent.com/${repository}/v2.4.1/${datasetPath}`,
  },
};

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Unable to download ${url}: ${response.status} ${response.statusText}`);
  return response.json();
}

function provinceName(fullName) {
  return String(fullName || "").replace(/^(Thành phố|Tỉnh)\s+/u, "");
}

const [currentSource, legacySource] = await Promise.all([
  fetchJson(sources.current.url),
  fetchJson(sources.legacy.url),
]);

const data = {
  meta: {
    source: `https://github.com/${repository}`,
    license: "MIT",
    currentRevision: sources.current.revision,
    legacyRevision: sources.legacy.revision,
  },
  legacy: legacySource.map((province) => [
    provinceName(province.FullName),
    (province.District || []).map((district) => [
      district.FullName,
      (district.Ward || []).map((ward) => ward.FullName),
    ]),
  ]),
  current: currentSource.map((province) => [
    provinceName(province.FullName),
    (province.Wards || []).map((ward) => ward.FullName),
  ]),
};

const output = `/*
 * Vietnamese administrative units for the Trinket address picker.
 * Source: ${data.meta.source} (${data.meta.license} license)
 * License notice: public/address-data.LICENSE.txt
 * Current two-level revision: ${data.meta.currentRevision}
 * Legacy three-level revision: ${data.meta.legacyRevision}
 * Generated by scripts/generate-address-data.mjs; do not edit manually.
 */
window.VIETNAM_ADDRESS_DATA=${JSON.stringify(data)};
`;

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(scriptDirectory, "../public/address-data.js");
await writeFile(outputPath, output, "utf8");

const legacyDistricts = data.legacy.reduce((total, province) => total + province[1].length, 0);
const legacyWards = data.legacy.reduce(
  (total, province) => total + province[1].reduce((districtTotal, district) => districtTotal + district[1].length, 0),
  0,
);
const currentWards = data.current.reduce((total, province) => total + province[1].length, 0);

console.log(
  `Wrote ${outputPath}: ${data.legacy.length} legacy provinces, ${legacyDistricts} districts, ${legacyWards} wards; `
  + `${data.current.length} current provinces, ${currentWards} wards.`,
);
